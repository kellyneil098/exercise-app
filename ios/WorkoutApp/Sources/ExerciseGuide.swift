/// Clock for a staged demonstration: each stage eases through its keyframe legs (`move` seconds each) and then
/// holds (`hold` seconds); the whole thing loops. `at(time)` says which stage is active and which two keyframes
/// the figure is between.
struct GuideTimeline {
    struct Sample { let stage: Int, from: Int, to: Int, t: CGFloat }

    let move: TimeInterval = 1.1
    let hold: TimeInterval = 0.8
    private var legs: [(stage: Int, from: Int, to: Int, start: TimeInterval, end: TimeInterval)] = []
    private var holds: [(stage: Int, frame: Int, start: TimeInterval, end: TimeInterval)] = []
    private(set) var period: TimeInterval = 0

    init(_ guide: ExerciseGuide) {
        var current = guide.startFrame, clock: TimeInterval = 0
        for (s, stage) in guide.stages.enumerated() {
            for f in stage.frames where f != current {
                legs.append((s, current, f, clock, clock + move)); clock += move; current = f
            }
            holds.append((s, current, clock, clock + hold)); clock += hold
        }
        period = max(clock, 0.01)
    }

    func at(_ time: TimeInterval) -> Sample {
        let u = time.truncatingRemainder(dividingBy: period)
        for l in legs where u >= l.start && u < l.end {
            let t = (u - l.start) / move
            return Sample(stage: l.stage, from: l.from, to: l.to, t: CGFloat((1 - cos(.pi * t)) / 2))
        }
        for h in holds where u >= h.start && u < h.end { return Sample(stage: h.stage, from: h.frame, to: h.frame, t: 0) }
        let last = holds.last!
        return Sample(stage: last.stage, from: last.frame, to: last.frame, t: 0)
    }

    /// The resting pose of a stage, for the static (reduce-motion / paused) view.
    func end(of stage: Int, in guide: ExerciseGuide) -> Int { guide.stages[stage].frames.last ?? guide.startFrame }
}
