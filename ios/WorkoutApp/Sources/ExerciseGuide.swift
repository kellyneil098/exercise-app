/// Technique guide behind a tap on a deck pictogram: a staged demonstration (the exercise's own pictogram keyframes
/// walked in a named order — set up, descend, drive...) plus written cues. Both parts record their *scope*: whether
/// they were written for this exact exercise or inherited from its movement family, so the UI can say so instead of
/// pretending. Content is reviewed against the sources listed in docs/exercise-guides.md.
///
/// The tables are generated from tools/pictograms/guides.py (`python3 motions.py guides`); edit them there.
struct ExerciseGuide {
    enum Scope { case exercise, family }
    enum Overlay { case joints, path, midfoot }

    struct Stage: Identifiable {
        let name: String
        let cue: String
        /// Keyframe indices the figure moves through in this stage; it holds on the last one.
        let frames: [Int]
        var id: String { name + frames.map(String.init).joined(separator: ",") }
    }

    struct Cues {
        let setUp: [String]
        let execute: [String]
        let avoid: [String]
        let breathing: String
    }

    struct Demonstration {
        let keyframes: [Pose]
        let anchor: Motion.Anchor
        let armsXY: Bool
        let plan: String
        let overlays: [Overlay]
        let motionScope: Scope
    }

    let exerciseKey: String
    let exerciseName: String
    let pattern: String
    let demonstration: Demonstration
    let stages: [Stage]
    let cues: Cues
    let cuesScope: Scope

    var familyName: String { Self.familyName(pattern: pattern) }
    /// The keyframe shown before the first stage begins (the last stage ends the loop there).
    var startFrame: Int { stages.last?.frames.last ?? 0 }
    /// Keyframe indices in loop order, starting and ending on `startFrame`.
    var loopOrder: [Int] { [startFrame] + stages.flatMap(\.frames) }

    static func `for`(exerciseKey: String, exerciseName: String, pattern: String) -> ExerciseGuide {
        let demo = Self.demonstration(exerciseKey: exerciseKey, pattern: pattern)
        let (written, scope) = Self.cues(exerciseKey: exerciseKey, pattern: pattern)
        return ExerciseGuide(exerciseKey: exerciseKey, exerciseName: exerciseName, pattern: pattern, demonstration: demo,
                             stages: Self.stages(plan: demo.plan), cues: written, cuesScope: scope)
    }

