def pose_json(p: Pose):
    d = {"hx": p.hx, "hy": p.hy, "torso": p.torso, "ua": p.ua, "fa": p.fa, "th": p.th, "sh": p.sh, "impl": p.impl, "props": list(p.props),
         "grounded": p.grounded, "floor": p.floor}
    for f in ("head", "ua2", "fa2", "th2", "sh2"):
        if getattr(p, f) is not None:
            d[f] = getattr(p, f)
    return d


def export_json():
    out = []
    for key, name, pattern in all_exercises():
        m = motion_for(key, pattern)
        out.append({"key": key, "name": name, "pattern": pattern, "a": pose_json(m.a), "b": pose_json(m.b),
                    "anchor": m.resolved_anchor(), "armsXY": m.arms_xy})
    return out


def fmt(v: float) -> str:
    s = f"{v:.1f}"
    return s[:-2] if s.endswith(".0") else s


def pose_swift(p: Pose) -> str:
    args = [fmt(p.hx), fmt(p.hy), fmt(p.torso), fmt(p.ua), fmt(p.fa), fmt(p.th), fmt(p.sh)]
    for f, name in (("head", "headAngle"), ("ua2", "upperArm2"), ("fa2", "forearm2"), ("th2", "thigh2"), ("sh2", "shin2")):
        if getattr(p, f) is not None:
            args.append(f"{name}: {fmt(getattr(p, f))}")
    if p.impl != "none":
        args.append(f"implement: .{p.impl}")
    if p.props:
        args.append("props: [" + ", ".join("." + q for q in p.props) + "]")
    if not p.grounded:
        args.append("grounded: false")
    if not p.floor:
        args.append("floor: false")
    return "Pose(" + ", ".join(args) + ")"


def motion_swift(m: Motion) -> str:
    extra = ""
    if m.anchor != "auto":
        extra += f", anchor: .{m.anchor}"
    if m.arms_xy:
        extra += ", armsXY: true"
    return f"Motion({pose_swift(m.a)},\n                   {pose_swift(m.b)}{extra})"


def export_swift() -> str:
    lines = ["    // Generated by tools/pictograms/motions.py — edit that file and rerun `python3 motions.py swift`.",
             "    static func base(exerciseKey key: String, pattern: String) -> Motion {", "        switch key {"]
    for k, m in TABLE.items():
        lines.append(f'        case "{k}":\n            return {motion_swift(m)}')
    lines += ["        default: break", "        }", "        switch pattern {"]
    for k, m in PATTERNS.items():
        lines.append(f'        case "{k}":\n            return {motion_swift(m)}')
    lines += [f"        default:\n            return {motion_swift(DEFAULT)}", "        }", "    }"]
    return "\n".join(lines)


