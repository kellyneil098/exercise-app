def motion_for(key: str, pattern: str) -> Motion:
    m = TABLE.get(key) or PATTERNS.get(pattern) or DEFAULT

    def fix(p: Pose) -> Pose:
        impl, props = p.impl, list(p.props)
        if "dumbbell" in key and impl == "barbell":
            impl = "dumbbell"
        if "barbell" in key and impl == "dumbbell":
            impl = "barbell"
        if "smith" in key and "smithRails" not in props:
            props.append("smithRails")
        return p.w(impl=impl, props=props)

    return Motion(fix(m.a), fix(m.b), m.anchor, m.arms_xy)


# ---------------------------------------------------------------- kinematics (mirrors Skeleton in Swift)
def seg(p, deg, length):
    r = math.radians(deg)
    return (p[0] + length * math.cos(r), p[1] + length * math.sin(r))


def lerp_pose(a: Pose, b: Pose, t: float) -> Pose:
    def L(x, y):
        if x is None or y is None:
            return x if y is None else y
        return x + (y - x) * t

    ha, hb = a.head if a.head is not None else a.torso, b.head if b.head is not None else b.torso
    return Pose(L(a.hx, b.hx), L(a.hy, b.hy), L(a.torso, b.torso), L(a.ua, b.ua), L(a.fa, b.fa), L(a.th, b.th), L(a.sh, b.sh),
                head=L(ha, hb), ua2=L(a.ua2, b.ua2), fa2=L(a.fa2, b.fa2), th2=L(a.th2, b.th2), sh2=L(a.sh2, b.sh2),
                impl=a.impl, props=a.props, grounded=a.grounded, floor=a.floor)


class Skeleton:
    def __init__(self, p: Pose):
        self.pose = p
        hip = (p.hx, p.hy)
        shoulder = seg(hip, p.torso, TORSO)
        head_angle = p.head if p.head is not None else p.torso
        head = seg(shoulder, head_angle, NECK)
        arms = []
        e = seg(shoulder, p.ua, UPPER_ARM)
        arms.append([e, seg(e, p.fa, FOREARM)])
        if p.ua2 is not None and p.fa2 is not None:
            e2 = seg(shoulder, p.ua2, UPPER_ARM)
            arms.append([e2, seg(e2, p.fa2, FOREARM)])
        legs = []
        k = seg(hip, p.th, THIGH)
        legs.append([k, seg(k, p.sh, SHIN), p.sh])
        if p.th2 is not None and p.sh2 is not None:
            k2 = seg(hip, p.th2, THIGH)
            legs.append([k2, seg(k2, p.sh2, SHIN), p.sh2])
        self.hip, self.shoulder, self.head, self.arms, self.legs, self.head_angle = hip, shoulder, head, arms, legs, head_angle
        if p.grounded:
            self.shift(0, FLOOR - max(l[1][1] for l in legs))

    def shift(self, dx, dy):
        mv = lambda q: (q[0] + dx, q[1] + dy)
        self.hip, self.shoulder, self.head = mv(self.hip), mv(self.shoulder), mv(self.head)
        self.arms = [[mv(a[0]), mv(a[1])] for a in self.arms]
        self.legs = [[mv(l[0]), mv(l[1]), l[2]] for l in self.legs]

    def anchor_point(self, mode):
        if mode == "foot":
            return self.legs[0][1]
        if mode == "foot2":
            return self.legs[-1][1]
        if mode == "hand":
            return self.arms[0][1]
        if mode == "shoulder":
            return self.shoulder
        return self.hip

    def anchor_to(self, ref: "Skeleton", mode: str):
        a, b = self.anchor_point(mode), ref.anchor_point(mode)
        dx = b[0] - a[0]
        dy = 0 if (self.pose.grounded and mode in ("foot", "foot2")) else b[1] - a[1]
        self.shift(dx, dy)

    @property
    def hand(self):
        return self.arms[0][1]

    @property
    def far_hand(self):
        return self.arms[-1][1]


def frames(m: Motion):
    """Anchored keyframe skeletons (A, B) and a sampler for the live skeleton at phase t in [0,1]."""
    anchor = m.resolved_anchor()
    ska = Skeleton(m.a)
    skb = Skeleton(m.b)
    skb.anchor_to(ska, anchor)

    def at(t: float) -> Skeleton:
        sk = Skeleton(lerp_pose(m.a, m.b, t))
        sk.anchor_to(ska, anchor)
        if m.arms_xy:
            s = sk.shoulder
            arms = []
            for i in range(len(sk.arms)):
                pa, pb = ska.arms[min(i, len(ska.arms) - 1)], skb.arms[min(i, len(skb.arms) - 1)]
                rel = lambda q, ref: (q[0] - ref.shoulder[0], q[1] - ref.shoulder[1])
                pts = []
                for j in range(2):
                    ra, rb = rel(pa[j], ska), rel(pb[j], skb)
                    pts.append((s[0] + ra[0] + (rb[0] - ra[0]) * t, s[1] + ra[1] + (rb[1] - ra[1]) * t))
                arms.append(pts)
            sk.arms = arms
        return sk

    return ska, skb, at


# ---------------------------------------------------------------- checks
HEAD_R = 5.4
FREE_STANDING_PROPS = {"calfBlock", "footBlock", "post", "supportRail", "supportBench", "smithRails"}


def com_check(m: Motion, key: str) -> list[str]:
    """Body (+ load) centre of mass must stay between heel and toe for free-standing poses."""
    warnings = []
    a = m.a
    if not a.grounded or m.resolved_anchor() not in ("foot", "foot2"):
        return warnings
    if set(a.props) - FREE_STANDING_PROPS or a.sh == 180 or a.impl == "wheel":
        return warnings
    _, _, at = frames(m)
    for t in (0, 0.25, 0.5, 0.75, 1):
        sk = at(t)
        parts = [(sk.hip, sk.shoulder, 0.42), (sk.shoulder, sk.head, 0.08)]
        for arm in sk.arms:
            parts += [(sk.shoulder, arm[0], 0.03), (arm[0], arm[1], 0.02)]
        for leg in sk.legs:
            parts += [(sk.hip, leg[0], 0.10), (leg[0], leg[1], 0.05)]
        mass = sum(w for *_, w in parts)
        cx = sum((p[0] + q[0]) / 2 * w for p, q, w in parts) / mass
        load = {"barbell": 0.6, "trapBar": 0.6, "dumbbell": 0.3, "dumbbellVertical": 0.3, "dumbbellFirst": 0.15, "kettlebell": 0.2}.get(a.impl, 0)
        if load:
            cx = (cx * 1 + sk.hand[0] * load) / (1 + load)
        feet = [l[1][0] for l in sk.legs if abs(l[1][1] - FLOOR) < 0.6]
        if not feet:
            continue
        heel, toe = min(feet) - 2.5, max(feet) + 5.5
        if not heel <= cx <= toe:
            warnings.append(f"{key}: t={t} COM x={cx:.1f} outside [{heel:.1f}, {toe:.1f}]")
    return warnings


def floor_check(m: Motion, key: str) -> list[str]:
    out = []
    _, _, at = frames(m)
    for t in (0, 0.5, 1):
        sk = at(t)
        pts = [("hip", sk.hip), ("shoulder", sk.shoulder), ("head", (sk.head[0], sk.head[1] + HEAD_R - 1.5))]
        pts += [(f"hand{i}", a[1]) for i, a in enumerate(sk.arms)] + [(f"elbow{i}", a[0]) for i, a in enumerate(sk.arms)]
        pts += [(f"knee{i}", l[0]) for i, l in enumerate(sk.legs)]
        for name, (x, y) in pts:
            if m.a.floor and y > FLOOR + 0.8:
                out.append(f"{key}: t={t} {name} below floor (y={y:.1f})")
    return out


def all_exercises():
    data = json.loads((REPO / "seed" / "exercises.json").read_text())["exercises"]
    return [(e["key"], e["name"], e["movement_pattern"]) for e in data]


def check():
    issues = []
    keys = {k for k, _, _ in all_exercises()}
    for k in TABLE:
        if k not in keys:
            issues.append(f"table key not in seed: {k}")
    for key, name, pattern in all_exercises():
        m = motion_for(key, pattern)
        issues += com_check(m, key) + floor_check(m, key)
    print("\n".join(issues) if issues else "all checks passed")
    return issues


