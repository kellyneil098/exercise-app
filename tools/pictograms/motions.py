@dataclass(frozen=True)
class Pose:
    hx: float
    hy: float
    torso: float
    ua: float
    fa: float
    th: float
    sh: float
    head: float | None = None
    ua2: float | None = None
    fa2: float | None = None
    th2: float | None = None
    sh2: float | None = None
    impl: str = "none"
    props: tuple[str, ...] = ()
    grounded: bool = True
    floor: bool = True

    def w(self, **edits) -> "Pose":
        if "props" in edits:
            edits["props"] = tuple(edits["props"])
        return replace(self, **edits)


@dataclass(frozen=True)
class Motion:
    a: Pose
    b: Pose
    anchor: str = "auto"  # auto | hip | foot | foot2 | hand | shoulder
    arms_xy: bool = False

    def resolved_anchor(self) -> str:
        if self.anchor != "auto":
            return self.anchor
        if not self.a.grounded and not self.a.floor:
            return "hand"
        return "foot" if self.a.grounded else "hip"


def P(*args, **kw) -> Pose:
    if "props" in kw:
        kw["props"] = tuple(kw["props"])
    return Pose(*args, **kw)


def M(a: Pose, b: Pose, anchor: str = "auto", arms_xy: bool = False) -> Motion:
    # B inherits A's far limbs / implement / props unless it sets them, so a keyframe never adds a limb.
    fill = {}
    for f in ("ua2", "fa2", "th2", "sh2"):
        if getattr(b, f) is None and getattr(a, f) is not None:
            fill[f] = getattr(a, f)
    if fill:
        b = b.w(**fill)
    return Motion(a, b, anchor, arms_xy)


