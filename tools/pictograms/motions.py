"""Source of truth for the exercise pictogram animations.

Each exercise is a Motion: two keyframe Poses (A, B) that the renderer eases between (A -> B -> A), an
anchor that stays put while the figure moves (the standing foot, the bar in the hands, the shoulders on
a bench...), and an optional `arms_xy` flag that interpolates the arm joints in Cartesian space so a
horizontal sweep foreshortens through the shoulder (fly / rear-delt / pec-deck family) instead of
swinging through the floor.

Angles are world degrees: 0 = toward the front (+x), 90 = down, -90 = up, 180 = behind. Unit box 100x60,
floor at y = 56.  Keep this file, the Swift table (generated by `python3 motions.py swift`) and the
report (`python3 motions.py report`) in sync by regenerating, never by hand-editing the outputs.
"""
